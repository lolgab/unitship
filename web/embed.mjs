// Embeds the built page in the panel: every file of <dist>, gzipped and in base64, as the Scala source <output>.
// The panel serves them as they are (Content-Encoding: gzip), so it stays one executable.
//
//   node embed.mjs dist ../panel/gen/Assets.scala
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { gzipSync } from 'node:zlib'

const [dist, output] = process.argv.slice(2)
if (!dist || !output) {
  console.error('usage: node embed.mjs <dist> <output.scala>')
  process.exit(2)
}

function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) yield* walk(path)
    else yield path
  }
}

const CHUNK = 16000 // a constant of a class file is limited to 65535 bytes
const entries = existsSync(dist) ? [...walk(dist)] : []
const files = entries.map((path) => {
  const base64 = gzipSync(readFileSync(path), { level: 9 }).toString('base64')
  const chunks = base64.match(new RegExp(`.{1,${CHUNK}}`, 'g')) ?? ['']
  return `    ${JSON.stringify('/' + relative(dist, path).split('\\').join('/'))} -> Array(\n${chunks.map((c) => `      "${c}"`).join(',\n')}\n    )`
})

mkdirSync(dirname(output), { recursive: true })
writeFileSync(
  output,
  `package panel

// Generated by web/embed.mjs: the files of the page, gzipped, in base64, in pieces. Do not edit.
object Assets {
  val files: Map[String, Array[String]] = Map(
${files.join(',\n')}
  )
}
`,
)
console.log(`embedded ${entries.length} files in ${output}`)
